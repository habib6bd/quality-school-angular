#!/usr/bin/env node
/**
 * Creates smaller WebP copies (`name-480.webp`, `name-960.webp`, `name-1440.webp`) of the school's
 * large photos and writes src/app/core/images/image-variants.generated.ts, which tells the app
 * which widths exist. Phones then download a 480-960 px file instead of the 1500 px original.
 *
 *   node scripts/generate-image-variants.mjs
 *
 * Only widths clearly smaller than the original are created. Originals are never modified.
 */
import { createRequire } from 'node:module';
import { readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const require = createRequire(import.meta.url);
const sharp = require('sharp');

const root = join(import.meta.dirname, '..');
const SOURCES = ['public/images/bqes/gallery'];
const WIDTHS = [480, 960, 1440];
const VARIANT = /-\d{3,4}\.webp$/; // a width suffix, not the "-1" in annual-sports-1.webp

const variants = {};
for (const dir of SOURCES) {
  for (const file of readdirSync(join(root, dir)).sort()) {
    if (!file.endsWith('.webp') || VARIANT.test(file)) continue;
    const path = join(root, dir, file);
    const { width } = await sharp(path).metadata();
    const widths = WIDTHS.filter((w) => w <= width * 0.9);
    for (const w of widths) {
      await sharp(path)
        .resize({ width: w })
        .webp({ quality: 78, effort: 5 })
        .toFile(path.replace(/\.webp$/, `-${w}.webp`));
    }
    variants[join(dir, file).replace(/^public\//, '')] = widths;
  }
}

const body = Object.entries(variants)
  .map(([src, widths]) => `  '${src}': [${widths.join(', ')}],`)
  .join('\n');
writeFileSync(
  join(root, 'src/app/core/images/image-variants.generated.ts'),
  `// Generated by scripts/generate-image-variants.mjs — do not edit.
/** Widths of the smaller copies that exist next to each large photo (\`name-<width>.webp\`). */
export const IMAGE_VARIANTS: Readonly<Record<string, readonly number[]>> = {
${body}
};
`,
);
console.log(`Variants written for ${Object.keys(variants).length} images.`);
